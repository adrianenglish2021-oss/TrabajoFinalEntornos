public class ConfiguracionCircadiana {
    private int minutosAumentoProgresivo;
    private boolean usarSonidosNaturaleza;

    public ConfiguracionCircadiana(int minutosAumentoProgresivo, boolean usarSonidosNaturaleza) {
        this.minutosAumentoProgresivo = minutosAumentoProgresivo;
        this.usarSonidosNaturaleza = usarSonidosNaturaleza;
    }
}